import { build } from 'vite'
import { chromium, expect } from '@playwright/test'
import config from '../vite.config.js'

const base = config({})
const built = await build({ ...base, configFile: false, logLevel: 'error',
  root: fileURLToPath(new URL('..', import.meta.url)),
  define: { ...base.define, 'process.env.NODE_ENV': '"production"' },
  build: { write: false, minify: false, cssCodeSplit: false, lib: { entry: fileURLToPath(new URL('./fixtures/promptProgramCard.ts', import.meta.url)), name: 'PromptProgramCardTest', formats: ['iife'] } },
})
const output = (Array.isArray(built) ? built : [built]).flatMap(result => result.output)
const css = output.find(item => item.type === 'asset' && item.fileName.endsWith('.css'))

async function open(t, choiceId) {
  const browser = await chromium.launch()
  t.after(() => browser.close())
  const page = await browser.newPage({ viewport: { width: 900, height: 900 } })
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.route('**/*', route => route.fulfill({ contentType: 'text/html', body: '<html class="dark"><body><div id="app"></div></body></html>' }))
  await page.goto('http://program-card.test/')
  if (css) await page.addStyleTag({ content: String(css.source) })
  await page.addScriptTag({ content: output.find(item => item.type === 'chunk').code })
  await page.evaluate(id => window.openChoice(id), choiceId)
  const card = page.locator('[data-program-card]')
  await card.waitFor()
  t.after(() => assert.deepEqual(errors, []))
  const option = text => card.locator(`[data-option="${text}"]`)
  const options = () => card.locator('[data-option]').evaluateAll(rows => rows.map(r => r.dataset.option))
  const all = card.locator('[data-all]')
  const count = card.locator('[data-count]')
  const state = id => page.evaluate(i => ({ pins: window.state().pins[i] || [], edit: window.state().edits[i] || {} }), id)
  return { page, card, option, options, all, count, state }
}

test('a short pick keeps the plain list: no search, everything ticked', async t => {
  const { card, options, option, all, count } = await open(t, 'mood')
  await expect(card.getByPlaceholder('Search')).toHaveCount(0)
  assert.deepEqual(await options(), ['calm', 'tense', 'joyful', 'wistful'])
  for (const o of await options()) await expect(option(o)).toHaveAttribute('aria-checked', 'true')
  await expect(all).toHaveText('All')
  await expect(all).toHaveAttribute('aria-checked', 'true')
  await expect(count).toHaveText('4')
  await expect(card.getByText('More like these')).toBeVisible()
  await expect(card.getByText('New set')).toBeVisible()
})

test('a long unbound pick filters as you type, in the list order; "Only these" keeps what is shown', async t => {
  const { page, card, options, all, count, state } = await open(t, 'color')
  const search = card.getByPlaceholder('Search')
  await expect(card.getByText('Only these')).toHaveCount(0)
  await search.fill('shade 1')
  const shown = ['shade 1', 'shade 10', 'shade 11', 'shade 12', 'shade 13', 'shade 14', 'shade 15']
  assert.deepEqual(await options(), shown)
  await expect(all).toContainText('All 7 shown')
  await card.getByText('Only these').click()
  await expect.poll(() => state('color')).toEqual({ pins: shown, edit: {} })
  await expect(count).toHaveText('7 of 15')
  await expect(page.locator('[data-choice="color"]')).toHaveText('Color:7 of 15')
  await search.fill('shade 7')
  assert.deepEqual(await options(), ['shade 7'])
  await expect(all).toHaveAttribute('aria-checked', 'false')
  // Nothing matches: the search becomes an option of its own, ticked.
  await search.fill('nothing like it')
  await expect(card.getByText('No matches')).toBeVisible()
  await card.getByText('Add “nothing like it”').click()
  await expect.poll(() => state('color')).toEqual({ pins: [...shown, 'nothing like it'], edit: { add: ['nothing like it'] } })
  await expect(search).toHaveValue('')
  // Escape clears the search and stops there; the next one belongs to the card.
  await search.fill('shade')
  await search.press('Escape')
  await expect(search).toHaveValue('')
  assert.equal(await page.evaluate(() => window.escapes()), 0)
})

test('a list-drawn pick is one flat list; unticking leaves a value out, Only narrows to one', async t => {
  const { page, card, option, options, all, count, state } = await open(t, 'expression')
  const pill = page.locator('[data-choice="expression"]')
  assert.equal((await options()).length, 29)
  assert.deepEqual((await options()).slice(9, 12), ['soft smile 10', 'wry frown 1', 'wry frown 2'])
  await expect(card.locator('[data-group]')).toHaveCount(0)
  await expect(card.getByText(/Usual|Rare|More ideas/)).toHaveCount(0)
  await expect(card.getByRole('button', { name: /Delete/ })).toHaveCount(0)
  await expect(count).toHaveText('29')
  await option('odd squint 2').click()
  await expect.poll(() => state('expression')).toEqual({ pins: [], edit: { out: ['odd squint 2'] } })
  await expect(option('odd squint 2')).toHaveAttribute('aria-checked', 'false')
  assert.equal((await options()).length, 29)  // left out, still listed
  await expect(count).toHaveText('28 of 29')
  await expect(all).toHaveAttribute('aria-checked', 'mixed')
  await expect(pill).toHaveText('Expression:28 of 29')
  await option('new grimace 3').hover()
  await option('new grimace 3').getByRole('button', { name: 'Only new grimace 3' }).click()
  await expect.poll(() => state('expression')).toEqual({ pins: ['new grimace 3'], edit: {} })
  await expect(pill).toHaveText('Expression:new grimace 3')
  // The All row ticks everything, then unticks everything: the detail is left out.
  await all.click()
  await expect.poll(() => state('expression')).toEqual({ pins: [], edit: {} })
  await expect(pill).toHaveText('Expression')
  await all.click()
  await expect.poll(() => state('expression')).toEqual({ pins: [], edit: { none: true } })
  await expect(count).toHaveText('0 of 29')
  await expect(all).toHaveAttribute('aria-checked', 'false')
  await expect(pill).toHaveText('Expression')
  await expect(pill.locator('.line-through')).toHaveCount(1)
  await option('wry frown 1').click()
  await expect.poll(() => state('expression')).toEqual({ pins: ['wry frown 1'], edit: {} })
})

